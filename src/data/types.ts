/* Domain model. These types are the contract between the data layer and the UI;
   real API adapters (src/services/adapters.ts) must return the same shapes. */

export type CategoryId =
  | 'outerwear'
  | 'tops'
  | 'knitwear'
  | 'trousers'
  | 'dresses'
  | 'shoes'
  | 'bags'
  | 'jewellery'
  | 'accessories';

export type ColourId =
  | 'black'
  | 'white'
  | 'ecru'
  | 'camel'
  | 'brown'
  | 'grey'
  | 'navy'
  | 'blue'
  | 'green'
  | 'olive'
  | 'red'
  | 'burgundy'
  | 'pink'
  | 'gold'
  | 'silver';

export type StyleTag =
  | 'vintage'
  | 'minimal'
  | 'oversized'
  | 'classic'
  | 'streetwear'
  | 'boho'
  | 'tailoring'
  | 'romantic'
  | 'casual'
  | 'party'
  | 'workwear'
  | 'sporty';

export type CityId = 'lisboa' | 'porto' | 'coimbra' | 'braga' | 'faro';

export interface GeoPoint {
  lat: number;
  lng: number;
}

export interface City extends GeoPoint {
  id: CityId;
  name: string;
}

export interface Brand {
  id: string;
  name: string;
  /** Short editorial line shown on brand chips and store pages. */
  tagline: string;
}

export type StoreType = 'boutique' | 'department' | 'vintage' | 'concept' | 'footwear';

export interface OpeningHours {
  /** 0 = Sunday … 6 = Saturday; null means closed. */
  [day: number]: { open: string; close: string } | null;
}

export interface Store extends GeoPoint {
  id: string;
  name: string;
  type: StoreType;
  city: CityId;
  neighbourhood: string;
  address: string;
  hours: OpeningHours;
  image: string;
  brandIds: string[];
  description: string;
  /** Partner integration level — determines how stock is sourced. */
  feed: 'manual' | 'csv' | 'api-demo';
}

export interface Product {
  id: string;
  name: string;
  brandId: string;
  category: CategoryId;
  price: number;
  /** Original price when on sale. */
  compareAt?: number;
  colours: ColourId[];
  sizes: string[];
  styles: StyleTag[];
  material: string;
  description: string;
  /** Extra search terms (pt-PT) to make the rule-based parser more forgiving. */
  keywords: string[];
  images: string[];
  /** Stores where this product is ranged. Inventory records only exist for these. */
  storeIds: string[];
  gender: 'women' | 'men' | 'unisex';
  isNew?: boolean;
}

/* ── Inventory ─────────────────────────────────────────────────────────────── */

/** Raw status as reported by the store/feed. */
export type ReportedStatus = 'in_stock' | 'low_stock' | 'out_of_stock' | 'unknown';

/** Status shown to users, after applying freshness rules. */
export type DisplayStatus = 'available' | 'low' | 'unconfirmed' | 'out';

export type InventorySource = 'store_manual' | 'csv_feed' | 'pos_api_demo';

export interface InventoryRecord {
  productId: string;
  storeId: string;
  size: string;
  colour: ColourId;
  status: ReportedStatus;
  /** Reported quantity, if the source provides one. Never treated as proof on its own. */
  quantity: number | null;
  lastUpdatedAt: string; // ISO
  source: InventorySource;
  verification: 'store_confirmed' | 'feed_reported' | 'unverified';
}

/** Aggregated availability for a product at a single store. */
export interface StoreAvailability {
  store: Store;
  status: DisplayStatus;
  distanceKm: number | null;
  lastUpdatedAt: string;
  source: InventorySource;
  verification: InventoryRecord['verification'];
  sizesAvailable: string[];
  records: InventoryRecord[];
}

/* ── Outfits ───────────────────────────────────────────────────────────────── */

export type OutfitSlot = 'outerwear' | 'top' | 'bottom' | 'dress' | 'shoes' | 'bag' | 'accessory';

export interface Outfit {
  id: string;
  name: string;
  mood: string;
  occasion: string;
  cover: string;
  items: Partial<Record<OutfitSlot, string>>; // slot → productId
  /** Editorial curation, user-saved, or generated by the outfit builder. */
  origin: 'editorial' | 'user';
  createdAt?: string;
}

/* ── User-owned data (persisted locally in the prototype) ──────────────────── */

export interface WardrobeItem {
  id: string;
  /** Linked catalogue product, if any. Manual items have none. */
  productId?: string;
  name: string;
  category: CategoryId;
  colour?: ColourId;
  size?: string;
  image?: string;
  notes?: string;
  addedAt: string;
  source: 'purchase' | 'manual' | 'discovered';
}

export interface Purchase {
  id: string;
  productId?: string;
  name: string;
  storeId?: string;
  storeName: string;
  date: string; // yyyy-mm-dd
  price: number;
  size?: string;
  colour?: ColourId;
  notes?: string;
  image?: string;
  addedToWardrobe: boolean;
}

export interface UserProfile {
  name: string;
  email: string;
  sizes: { tops: string; bottoms: string; shoes: string };
  colours: ColourId[];
  categories: CategoryId[];
  brands: string[];
  budgetMax: number;
  radiusKm: number;
  city: CityId;
  language: 'pt-PT' | 'es-ES';
  privacy: { personalisedRecs: boolean; shareAnalytics: boolean };
  notifications: { priceDrops: boolean; savedSearches: boolean; newsletter: boolean };
  /** Apply profile sizes/colours to search by default. */
  applyPrefsToSearch: boolean;
}

export type PlanId = 'free' | 'plus';
export type BillingCycle = 'monthly' | 'annual';

export interface SubscriptionPlan {
  id: PlanId;
  name: string;
  monthly: number;
  annual: number;
  blurb: string;
  features: { label: string; included: boolean | string }[];
}

export interface Subscription {
  plan: PlanId;
  cycle?: BillingCycle;
  since?: string;
  simulated: true;
}

export interface Inspiration {
  id: string;
  title: string;
  image: string;
  /** Attributes the simulated visual search will "detect" for this image. */
  detected: { category: CategoryId; colours: ColourId[]; styles: StyleTag[]; label: string };
}
